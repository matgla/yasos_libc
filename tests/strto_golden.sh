#!/bin/sh
# The golden table of atoi_tests.c: glibc's strtoll / strtoull (64-bit build)
# and strtol / strtoul (-m32: the device's 32-bit long) for every input in
# strto_golden.inc's INPUTS at every base in BASES.  atoi_tests.c runs on QEMU
# against bare-metal newlib, which is no oracle (it reads "0x" as no number at
# all), so glibc's answers are kept as data.
#
#   sh strto_golden.sh > strto_golden.inc     (needs gcc and 32-bit glibc)
#
# -std=c11: glibc reads the 0b prefix only in C23 (__isoc23_strtoull), so the
# inputs stay clear of it; atoi_tests.c asserts the prefix on its own.
set -e
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cat >"$tmp/inputs.h" <<'EOF'
/* the inputs that mattered, and the hard ones: the prefixes, the limits
 * either side (64-bit and 32-bit), strings that are not numbers, `1b`/`1f`
 * (local labels to an assembler: stopping on the right character is the
 * answer), the punctuation on either side of the letters, every blank */
static const char *const INPUTS[] = {
    "10", "100", "0xCCCD", "0xCCCC", "1b", "1f", "4", "0", "0777", "0x0",
    "  42", "-17", "+9", "0X1F", "abc", "", "0x", "7z", "  -0x10zz",
    "  \t 0755q", "-0", "1103515245", "\n\v\f\r 12", "- 5", "+-5", "--5",
    "0xg", "-0x", "0x-5", "0b2", "Zz", "zz",
    /* punctuation between '9' and 'A' and past 'Z' / 'z' is not a digit: sed
     * parses the ';' after "s/^/X/" with strtol, and read it as 4 */
    ";", "; s/x/Y/", ":7", "@1", "9:", "5;", "Z[", "z{", "`1", "[1", "{",
    "  -", "+", " -x",
    /* the 64-bit limits */
    "12345678901234567890", "9223372036854775807", "-9223372036854775808",
    "9223372036854775808", "-9223372036854775809", "18446744073709551615",
    "18446744073709551616", "-18446744073709551615", "-18446744073709551616",
    "999999999999999999999999", "0xFFFFFFFFFFFFFFFF", "0x10000000000000000",
    "1zzzzzzzzzzzzz", "000000000000000000000000000001",
    /* the 32-bit limits: strtol and strtoul narrow on the device */
    "2147483647", "2147483648", "-2147483648", "-2147483649", "4294967295",
    "4294967296", "-4294967295", "-4294967296", "0x7fffffff", "0x80000000",
    "-0x80000000", "0xffffffff", "0x100000000", "-1", "  -1",
};
static const int BASES[] = {0, 2, 8, 10, 16, 36};
EOF

cat >"$tmp/gen.c" <<'EOF'
#include <errno.h>
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include "inputs.h"

static void quote(const char *s)
{
  putchar('"');
  for (; *s; s++)
    switch (*s) {
    case '\t': fputs("\\t", stdout); break;
    case '\n': fputs("\\n", stdout); break;
    case '\v': fputs("\\v", stdout); break;
    case '\f': fputs("\\f", stdout); break;
    case '\r': fputs("\\r", stdout); break;
    case '"': case '\\': putchar('\\'); /* fall through */
    default: putchar(*s);
    }
  putchar('"');
}

int main(void)
{
  for (size_t i = 0; i < sizeof INPUTS / sizeof *INPUTS; i++)
    for (size_t b = 0; b < sizeof BASES / sizeof *BASES; b++) {
      const char *s = INPUTS[i];
      char *e1, *e2;
      int base = BASES[b];
#if LONG_MAX > 0x7fffffffL
      errno = 0;
      long long v = strtoll(s, &e1, base);
      int r1 = errno == ERANGE;
      errno = 0;
      unsigned long long u = strtoull(s, &e2, base);
      int r2 = errno == ERANGE;
      printf("    {");
      quote(s);
      if (v == LLONG_MIN)
        printf(", %d, LLONG_MIN, %d, %d, ", base, (int)(e1 - s), r1);
      else
        printf(", %d, %lldLL, %d, %d, ", base, v, (int)(e1 - s), r1);
      printf("%lluULL, %d, %d,\n", u, (int)(e2 - s), r2);
#else
      errno = 0;
      long v = strtol(s, &e1, base);
      int r1 = errno == ERANGE;
      errno = 0;
      unsigned long u = strtoul(s, &e2, base);
      int r2 = errno == ERANGE;
      if (v == LONG_MIN)
        printf("     LONG_MIN, %d, %d, ", (int)(e1 - s), r1);
      else
        printf("     %ldL, %d, %d, ", v, (int)(e1 - s), r1);
      printf("%luUL, %d, %d},\n", u, (int)(e2 - s), r2);
#endif
    }
  return 0;
}
EOF

gcc -std=c11 -O1 -I"$tmp" "$tmp/gen.c" -o "$tmp/gen64"
gcc -m32 -std=c11 -O1 -I"$tmp" "$tmp/gen.c" -o "$tmp/gen32"
"$tmp/gen64" >"$tmp/64"
"$tmp/gen32" >"$tmp/32"

echo "/* Generated by strto_golden.sh from $(ldd --version | head -1 | sed 's/^ldd //'): do not edit. */"
echo "/* yasc (atoi_tests.c), which is said per file: the strings are views */"
echo "#pragma yasc"
echo
cat "$tmp/inputs.h"
echo
echo "/* input, base, then glibc's strtoll / strtoull (64-bit) and strtol / strtoul"
echo "   (32-bit long): value, characters converted, ERANGE */"
echo "static const struct strto_golden {"
echo "  const char * view input;"
echo "  int base;"
echo "  long long ll; int ll_end, ll_range;"
echo "  unsigned long long ull; int ull_end, ull_range;"
echo "  long l; int l_end, l_range;"
echo "  unsigned long ul; int ul_end, ul_range;"
echo "} GOLDEN[] = {"
paste -d '\n' "$tmp/64" "$tmp/32"
echo "};"
